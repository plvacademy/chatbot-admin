const NO_NAME = [
  ['I’m {name}, PLV’s', 'I’m PLV’s'], ['I’m {name}.', 'I’m PLV’s assistant.'], ['{name} here from PLV', 'PLV’s assistant here'],
  ['أنا {name}، مساعد PLV', 'أنا مساعد PLV'], ['أنا {name}، المساعد', 'أنا المساعد'], ['أنا {name} من PLV', 'أنا مساعد PLV'], ['معاك {name}', 'معاك مساعد PLV'],
];
const unnamed = (s, vars) => ('name' in vars && !String(vars.name || '').trim()
  ? NO_NAME.reduce((acc, [from, to]) => acc.split(from).join(to), s) : s);
